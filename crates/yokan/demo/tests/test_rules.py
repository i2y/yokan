"""The Python a code generator writes, put through the dialect as written.

Each directory under `rules/` holds what rulec wrote for one business
rule — the module byte for byte, its interface and its vectors — and the
app `tools/rule_apps.py` writes from them, which calls the rule with every
vector's input and prints what came out. The sweep gates each app, which
holds the compiled run to CPython's; these tests hold CPython's run to the
vectors, which hold the rule's own evaluator. The three then agree: the
evaluator that wrote the answers, CPython, and the binary.
"""
import contextlib
import importlib.util
import io
import os

from yokan_testing import import_app, run_script

HERE = os.path.dirname(os.path.abspath(__file__))
RULES = os.path.join(HERE, "rules")
TOOL = os.path.join(HERE, "..", "..", "tools", "rule_apps.py")

# The tool is a script, not a package: loaded by its path, the way the
# plugin loads an app.
_spec = importlib.util.spec_from_file_location("rule_apps", TOOL)
assert _spec is not None and _spec.loader is not None
rule_apps = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rule_apps)

NAMES = sorted(
    d for d in os.listdir(RULES) if os.path.isfile(os.path.join(RULES, d, "app.py"))
)


def printed(name: str) -> list:
    """What the app printed under CPython: the interpreted run."""
    app = import_app(os.path.join(RULES, name, "app.py"))
    said = io.StringIO()
    with contextlib.redirect_stdout(said):
        run_script(app, "", on_start=app.check)
    return said.getvalue().splitlines()


def test_cpython_prints_what_the_vectors_expect():
    wrong = []
    for name in NAMES:
        got = printed(name)
        want = rule_apps.Rule(os.path.join(RULES, name)).expected_lines()
        first = next((i for i, (g, w) in enumerate(zip(got, want)) if g != w), None)
        if first is not None:
            wrong.append(f"{name}: line {first + 1} printed {got[first]!r}, the vectors say {want[first]!r}")
        elif len(got) != len(want):
            wrong.append(f"{name}: {len(got)} lines printed, the vectors have {len(want)}")
    assert not wrong, "\n".join(wrong)


def test_the_apps_are_what_the_tool_writes():
    # The apps are written from the vectors; one edited by hand, or left
    # behind when the vectors moved, would be testing something else.
    stale = []
    for name in NAMES:
        root = os.path.join(RULES, name)
        with open(os.path.join(root, "app.py"), encoding="utf-8") as f:
            if f.read() != rule_apps.Rule(root).app():
                stale.append(f"uv run tools/rule_apps.py {os.path.relpath(root)}")
    assert not stale, "\n".join(stale)


def test_the_modules_are_the_generators_own():
    # Nothing in a module is changed to fit the dialect: the file is the
    # one the generator wrote, which says so on its first line.
    for name in NAMES:
        with open(os.path.join(RULES, name, f"{name}.py"), encoding="utf-8") as f:
            assert f.readline().startswith("# Code generated by rulec "), name
